#!/usr/bin/env python
"""Generate ``site/src/country.generated.js`` from the active country config.

The front-end is country-agnostic: every country-specific value (map centre,
geocoder filter, PMTiles URLs, title) is read here and written to a small ES
module that ``site/src/constants.js`` imports. Run this after changing
``config.yaml`` or a profile, or let ``make site_dev`` / ``make site_build`` do
it automatically.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

from openpois.config import country_code, load_config

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_PATH = REPO_ROOT / "site" / "src" / "country.generated.js"

DEFAULT_SITE = {
    "title": "OpenPOIs",
    "locale": "en-US",
    "timezone": "UTC",
    "initial_center": [-73.9855, 40.758],
    "initial_zoom": 18,
    "bbox": None,
    "geocoder_country": "US",
}


def _site_config(config) -> dict:
    site = dict(DEFAULT_SITE)
    site.update(config.get("site", fail_if_none = False) or {})
    return site


def _pmtiles_base(config, site: dict) -> str:
    """Return the public version folder that holds the three PMTiles archives.

    ``OPENPOIS_PMTILES_BASE_URL`` wins so a local run can point the site at a
    local static server without editing a country profile.
    """
    env_base = os.environ.get("OPENPOIS_PMTILES_BASE_URL")
    if env_base:
        return env_base.rstrip("/")
    explicit = site.get("pmtiles_base_url")
    if explicit:
        return str(explicit).rstrip("/")
    public_base = str(config.get("publish", "public_base_url")).rstrip("/")
    version = config.get("versions", "source_coop")
    return f"{public_base}/{version}"


def _js(value) -> str:
    return json.dumps(value, ensure_ascii = False)


def build_module(config) -> str:
    site = _site_config(config)
    country = config.get("country", fail_if_none = False)
    if not isinstance(country, dict):
        country = {"iso2": country_code(config)}

    base = _pmtiles_base(config, site)
    country_name = country.get("name") or country_code(config)
    title = site.get("title") or f"OpenPOIs {country_name}"
    urls = {
        "osm": f"{base}/osm-pmtiles/osm.pmtiles",
        "conflated": f"{base}/conflated-pmtiles/conflated.pmtiles",
        "overture": f"{base}/overture-pmtiles/overture.pmtiles",
        "categories": f"{base}/overture-pmtiles/overture_categories.json",
    }
    lines = [
        "// Generated by scripts/build_site_config.py — do not edit by hand.",
        f"// Source: config.yaml + country profile for {country_code(config)}.",
        "",
        f"export const COUNTRY = {_js(country)}",
        f"export const COUNTRY_CODE = {_js(country_code(config))}",
        f"export const COUNTRY_NAME = {_js(country_name)}",
        f"export const SITE_TITLE = {_js(title)}",
        f"export const SITE_LOCALE = {_js(site.get('locale'))}",
        f"export const SITE_TIMEZONE = {_js(site.get('timezone'))}",
        f"export const INITIAL_CENTER = {_js(site.get('initial_center'))}",
        f"export const INITIAL_ZOOM = {_js(site.get('initial_zoom'))}",
        f"export const MAP_BBOX = {_js(site.get('bbox'))}",
        f"export const GEOCODER_COUNTRY = {_js(site.get('geocoder_country'))}",
        "",
        f"export const OSM_PMTILES_URL = {_js(urls['osm'])}",
        f"export const CONFLATED_PMTILES_URL = {_js(urls['conflated'])}",
        f"export const OVERTURE_PMTILES_URL = {_js(urls['overture'])}",
        f"export const OVERTURE_CATEGORIES_URL = {_js(urls['categories'])}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    config = load_config()
    OUTPUT_PATH.parent.mkdir(parents = True, exist_ok = True)
    OUTPUT_PATH.write_text(build_module(config), encoding = "utf-8")
    country_name = config.get("country", "name", fail_if_none = False)
    print(
        f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)} "
        f"for {country_code(config)} ({country_name})"
    )


if __name__ == "__main__":
    main()
